const nftContractAddr = '0x5fbdb2315678afecb367f032d93f642f64180aa3';

// Pinata Api key and Secret
const pinataApiKey = String(import.meta.env.VITE_PINATA_API_KEY)
const pinataApiSecret = String(import.meta.env.VITE_PINATA_API_SECRET)



function UploadForm() {


    const [file, setFile] = useState(null);

    const handleFileChange = async (e) => {
        setFile(e.target.files[0]);
    }

    const handleSubmission = async (e) => {
        e.preventDefault();

        // initialize a contract
        const provider = new ethers.BrowserProvider(window.ethereum);
        await provider.send("eth_requestAccounts", []);
        const signer = await provider.getSigner();
        const contract = new ethers.Contract(nftContractAddr, nftContractABI, signer);

        // getting the user Address (to)
        const userAddress = signer.getAddress();

        if (!file) {
            console.error("No file selected for upload");
            return;
        }

        const formData = new FormData();
        formData.append('file', file);

        // Pinata api key call
        try {
            const res = await axios.post("https://api.pinata.cloud/pinning/pinFileToIPFS", formData, {
                headers: {
                    'pinata_api_key': pinataApiKey,
                    'pinata_secret_api_key': pinataApiSecret,
                    'Content-Type': 'multipart/form-data'
                }
            });

            const metaDataURL = `https://gateway.pinata.cloud/ipfs/${res.data.IpfsHash}`;

            // calling the mintDocument function from the smart contract with the user address and IPFS URL
            const tx = await contract.mintDocument(userAddress, metaDataURL);
            await tx.wait();
            console.log("Transaction confirmed");

        } catch (error) {
            console.log("Error in Axios Call", error);
        }

    }

    return (

        <>
            <div className="bg-[#3B3C65] text-white p-6 rounded-lg">
                <h2 className="mb-4 text-xl">Upload Your Document</h2>
                <form onSubmit={handleSubmission}>
                    <input
                        type="file"
                        onChange={handleFileChange}
                        accept=".pdf,.doc,.docx"
                        className="mb-2 p-2 border border-gray-600 rounded"
                        required
                    />
                    <button
                        type="submit"
                        className="bg-zinc-900 text-white py-2 px-4 mx-3 rounded hover:bg-[#4338CA]"
                    >
                        Mint Document as NFT
                    </button>
                </form>
            </div>
        </>
    )
}

export default UploadForm
